"""CPU tests using generated data; no copyrighted layout fixtures are bundled."""
import hashlib
import json
from pathlib import Path
import random
import struct

from build import ROOT, require, resource_table


def fnv64(data):
    value = 0xcbf29ce484222325
    for byte in data:
        value = ((value ^ byte) * 0x100000001b3) & 0xffffffffffffffff
    return value


def run_resource(config, patches, data, hook_index, relocation=0, table=None, flags=0):
    import unicorn as uc
    from unicorn import arm64_const as r
    u = uc.Uc(uc.UC_ARCH_ARM64, uc.UC_MODE_ARM)
    pages = set()
    for patch in patches:
        pages.update(range(patch['address'] & ~4095,
                           (patch['address'] + len(patch['new']) + 4095) & ~4095, 4096))
    for page in sorted(pages):
        u.mem_map(relocation + page, 4096)
    for patch in patches:
        u.mem_write(relocation + patch['address'], patch['new'])
    if table is not None:
        u.mem_write(relocation + int(config['table_address'], 16), table)
    u.mem_map(0x100000, (len(data) + 8191) & ~4095)
    u.mem_write(0x100000, bytes(data))
    u.mem_map(0x200000, 0x4000)
    u.mem_write(0x200000, b'\xA5' * 0x4000)
    for i in range(29):
        u.reg_write(r.UC_ARM64_REG_X0 + i, 0x123400 + i)
    for i in range(32):
        u.reg_write(r.UC_ARM64_REG_Q0 + i, (i + 1) * 0x1000000000000000100000001)
    u.reg_write(r.UC_ARM64_REG_FP, 0x202000)
    u.reg_write(r.UC_ARM64_REG_LR, 0x12345678)
    u.reg_write(r.UC_ARM64_REG_SP, 0x203ff0)
    u.reg_write(r.UC_ARM64_REG_X19, 0x100000)
    u.reg_write(r.UC_ARM64_REG_X20, 0x200000)
    u.reg_write(r.UC_ARM64_REG_X21, 0x100000)
    u.reg_write(r.UC_ARM64_REG_NZCV, flags)
    regs = [r.UC_ARM64_REG_X0 + i for i in range(29)]
    regs += [r.UC_ARM64_REG_FP, r.UC_ARM64_REG_LR, r.UC_ARM64_REG_SP, r.UC_ARM64_REG_NZCV]
    regs += [r.UC_ARM64_REG_Q0 + i for i in range(32)]
    before = {reg: u.reg_read(reg) for reg in regs}
    hook = config['hooks'][hook_index]
    site = relocation + int(hook['site'], 16)
    u.emu_start(site, site + 4, count=5_000_000)
    require(u.reg_read(r.UC_ARM64_REG_PC) == site + 4, 'Resource hook did not return')
    if hook_index == 2:
        before[r.UC_ARM64_REG_X8] = struct.unpack_from('<H', data, 6)[0]
        require(bytes(u.mem_read(0x200000, 8)) == b'\xA5' * 8, 'Layout hook changed unrelated object')
    else:
        require(bytes(u.mem_read(0x200000, 8)) == struct.pack('<Q', 0x100000), 'Animation hook failed to replay store')
    require({reg: u.reg_read(reg) for reg in regs} == before, 'Resource hook changed registers, SIMD, flags, or SP')
    return bytes(u.mem_read(0x100000, len(data)))


def verify_resource_hooks(config, patches):
    resources = json.loads((ROOT / 'layout_deltas.json').read_text())
    rng = random.Random(30334401440)
    cases = 0
    for item in resources:
        # Unique, generated bytes exercise every shipped offset and replacement.
        data = bytearray(rng.randbytes(item['size']))
        struct.pack_into('<H', data, 6, 20)
        struct.pack_into('<I', data, 12, len(data))
        for change in item['changes']:
            data[change['offset']:change['offset']+4] = bytes.fromhex(change['before'])
        fixture = dict(item, fnv64=f'{fnv64(data):016x}')
        # A preceding same-size nonmatch exercises traversal as well as hashing.
        decoy = dict(fixture, fnv64=f'{fnv64(data) ^ 1:016x}')
        table = resource_table([decoy, fixture])
        expected = bytearray(data)
        for change in item['changes']:
            expected[change['offset']:change['offset']+4] = bytes.fromhex(change['after'])
        for base in (0, 0x7100000000):
            for hook_index in (2, 3):
                for flags in (0, 0x90000000, 0x60000000, 0xf0000000):
                    got = run_resource(config, patches, data, hook_index, base, table, flags)
                    require(got == expected, 'Resource result differs outside/inside approved deltas')
                    again = run_resource(config, patches, got, hook_index, base, table, flags)
                    require(again == got, 'Repeated load accumulated changes')
                    corrupted = bytearray(data); corrupted[18] ^= 0x80
                    require(run_resource(config, patches, corrupted, hook_index, base, table, flags) == corrupted,
                            'Unexpected resource fingerprint was modified')
                    cases += 3
    return dict(executions=cases, resources=len(resources), load_bases=2,
                generated_fixtures=True, exact_write_ranges=True, idempotence=True,
                changed_resource_rejected=True, gameplay_confirmed=False)


def verify_local_resources(directory, config, patches):
    resources = json.loads((ROOT / 'layout_deltas.json').read_text())
    for item in resources:
        data = (Path(directory) / item['resource'].split('/')[-1]).read_bytes()
        require(len(data) == item['size'] and hashlib.sha256(data).hexdigest() == item['sha256'], 'Unexpected local resource')
        require(f'{fnv64(data):016x}' == item['fnv64'], 'Resource fingerprint mismatch')
        expected = bytearray(data)
        for change in item['changes']:
            at = change['offset']
            require(data[at:at+4].hex() == change['before'], 'Unexpected original resource field')
            expected[at:at+4] = bytes.fromhex(change['after'])
        index = 2 if item['resource'].endswith('.bflyt') else 3
        for base in (0, 0x7100000000):
            got = run_resource(config, patches, data, index, base)
            require(got == expected and hashlib.sha256(got).hexdigest() == item['patched_sha256'], 'Actual resource CPU test failed')
            require(run_resource(config, patches, got, index, base) == got, 'Actual resource repeated-load test failed')
    return dict(resources=len(resources), executions=4*len(resources), status='passed', gameplay_confirmed=False)
